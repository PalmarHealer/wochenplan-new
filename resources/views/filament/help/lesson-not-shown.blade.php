<p>Wenn ein Angebot in der Tagesansicht, im PDF oder im Schichtplan fehlt, liegt es fast immer an einem dieser Punkte:</p>
<ol>
    <li><strong>Anderes Layout an dem Tag.</strong> Angebote erscheinen nur in Zellen, die im Layout des Tages genau diesen Raum
        und diese Zeit haben. In Ferien, an Feiertagen oder an besonderen Tagen gilt oft ein eigenes Layout.
        Das Angebot ist dann nicht gelöscht, nur unsichtbar.</li>
    <li><strong>Ein einzelnes Angebot ersetzt es.</strong> Gibt es im selben Slot ein Angebot nur für diesen Tag,
        wird das wiederholende Angebot an dem Tag nicht angezeigt. Das gilt auch, wenn die „Nur heute“-Kopie in einen anderen Slot verschoben wurde.</li>
    <li><strong>Zwei Angebote im selben Slot.</strong> Pro Raum und Zeit wird nur eins angezeigt. Die Belegung siehst du beim Bearbeiten in der Slot-Auswahl.</li>
    <li><strong>Wiederholendes Angebot zu neu oder gelöscht.</strong> Es gilt erst ab dem Tag, an dem es angelegt wurde, und nicht mehr nach dem Löschtag.</li>
    <li><strong>Raum gelöscht.</strong> Wurde der Raum eines Angebots gelöscht, hat das Angebot keinen Slot mehr.</li>
</ol>
<p>
    Ein ausgefallenes Angebot fehlt dagegen nicht. Es wird durchgestrichen angezeigt.
</p>
